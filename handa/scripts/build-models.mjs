#!/usr/bin/env node
/**
 * Builds the cartoon item assets:
 *   public/models/<shape>.glb           one neutral-colour GLB per ItemShape
 *   public/sprites/<itemId>.webp        pre-rendered 256 px sprite per catalog item
 *   public/sprites/<itemId>--6.webp     six-pack variant (bottle shapes)
 *   public/sprites/<itemId>--3.webp     can-row variant (can shapes)
 *   src/models/manifest.ts              SPRITES + MODELS lookup tables
 *
 * It starts a Vite dev server (or reuses one on --port) and drives
 * tools/render/index.html with headless Chromium (software GL is fine).
 *
 *   node scripts/build-models.mjs [--port 5180] [--sheet out.png] [--only water-bottle-1l,drum]
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import pw from '/opt/node-tools/node_modules/playwright/index.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (name, def) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : def; };
const PORT = Number(opt('--port', '5180'));
const SHEET = opt('--sheet', '');
const ONLY = opt('--only', '').split(',').filter(Boolean);
const URL = `http://127.0.0.1:${PORT}/tools/render/index.html`;
const MAX_WEBP = 14 * 1024, MAX_GLB = 60 * 1024;

const spritesDir = path.join(ROOT, 'public', 'sprites');
const modelsDir = path.join(ROOT, 'public', 'models');
fs.mkdirSync(spritesDir, { recursive: true });
fs.mkdirSync(modelsDir, { recursive: true });

async function up() { try { const r = await fetch(URL); return r.ok; } catch { return false; } }

let vite = null;
if (!(await up())) {
  // spawn the real binary (not via npx) so vite.kill() reaches the server process
  vite = spawn(path.join(ROOT, 'node_modules', '.bin', 'vite'), ['--port', String(PORT), '--strictPort', '--host', '127.0.0.1'], { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] });
  vite.stderr.on('data', (d) => process.stderr.write(`[vite] ${d}`));
  const t0 = Date.now();
  while (!(await up())) {
    if (Date.now() - t0 > 30000) { console.error('vite did not start'); process.exit(1); }
    await new Promise((r) => setTimeout(r, 300));
  }
  console.log(`vite dev server started on :${PORT}`);
} else console.log(`using existing server on :${PORT}`);

const browser = await pw.chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(URL);
await page.waitForFunction(() => window.__ready === true, null, { timeout: 60000 });

const items = await page.evaluate(() => window.__items());
const shapes = await page.evaluate(() => window.__shapes());
const wanted = ONLY.length ? items.filter((i) => ONLY.includes(i.id)) : items;

const SPRITES = {};
let spriteBytes = 0, big = [];
for (const it of wanted) {
  for (const v of ['', ...it.variants]) {
    const key = v ? `${it.id}--${v}` : it.id;
    const r = await page.evaluate(([id, variant]) => window.__render(id, variant), [it.id, v]);
    const buf = Buffer.from(r.dataUrl.split(',')[1], 'base64');
    fs.writeFileSync(path.join(spritesDir, `${key}.webp`), buf);
    spriteBytes += buf.length;
    if (buf.length > MAX_WEBP) big.push(`${key}.webp ${(buf.length / 1024).toFixed(1)} KB`);
    SPRITES[key] = { src: `sprites/${key}.webp`, w: r.w, h: r.h, base: r.base };
  }
}
console.log(`${Object.keys(SPRITES).length} sprites, ${(spriteBytes / 1024).toFixed(0)} KB`);

const MODELS = {};
let glbBytes = 0;
if (!ONLY.length) {
  for (const shape of shapes) {
    const b64 = await page.evaluate((s) => window.__exportGlb(s), shape);
    const buf = Buffer.from(b64, 'base64');
    fs.writeFileSync(path.join(modelsDir, `${shape}.glb`), buf);
    glbBytes += buf.length;
    if (buf.length > MAX_GLB) big.push(`${shape}.glb ${(buf.length / 1024).toFixed(1)} KB`);
    MODELS[shape] = `models/${shape}.glb`;
  }
  console.log(`${shapes.length} models, ${(glbBytes / 1024).toFixed(0)} KB`);
}

if (SHEET) {
  await page.evaluate(() => window.__contactSheet());
  await page.waitForTimeout(500);
  await page.locator('#sheet').screenshot({ path: SHEET });
  console.log(`contact sheet → ${SHEET}`);
}

if (!ONLY.length) {
  const manifestPath = path.join(ROOT, 'src', 'models', 'manifest.ts');
  const lines = [
    '/* eslint-disable */',
    '// GENERATED by scripts/build-models.mjs — do not edit. Re-run `pnpm models`.',
    "import type { ItemShape } from '@/domain/types';",
    '',
    'export interface SpriteEntry { src: string; w: number; h: number; base: number }',
    '',
    '/** Pre-rendered item sprites (paths relative to the site base). `base` = contact point y / height. */',
    'export const SPRITES: Record<string, SpriteEntry> = {',
    ...Object.entries(SPRITES).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  '${k}': { src: '${v.src}', w: ${v.w}, h: ${v.h}, base: ${v.base} },`),
    '};',
    '',
    '/** One neutral-colour GLB per shape (viewer recolours the `body` materials). */',
    'export const MODELS: Record<ItemShape, string> = {',
    ...Object.entries(MODELS).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  ${k}: '${v}',`),
    '};',
    '',
  ];
  fs.writeFileSync(manifestPath, lines.join('\n'));
  console.log(`manifest → ${path.relative(ROOT, manifestPath)}`);
}

console.log(`total ${((spriteBytes + glbBytes) / 1024).toFixed(0)} KB`);
if (big.length) console.warn('over budget:\n  ' + big.join('\n  '));
if (errors.length) console.warn('page errors:\n  ' + errors.join('\n  '));

await browser.close();
if (vite) vite.kill();
process.exit(big.length || errors.length ? 2 : 0);
